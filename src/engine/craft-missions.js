/**
 * Landing sites as objects on the ground.
 *
 * Hardware that reached a surface is still there, at coordinates measured off
 * orbital imagery, so it belongs in the scene as much as anything in orbit
 * does. The Apollo descent stages, the Luna and Chang'e landers, the Vikings
 * and the Veneras are all placed from craft-data.js rather than from a
 * trajectory: a fixed point on a rotating body is a better description of them
 * than an ephemeris would be.
 *
 * Sites already reached by a craft in the roster above are skipped, because
 * that craft flies its real approach and then lands on the same spot.
 */
const CLAIMED_SITES = new Set(
  MISSIONS.map((m) => m.surfaceAfter?.site).filter(Boolean),
);

// Sites where the position is a best estimate rather than a measurement: no
// imagery to register against, or published figures that disagree by degrees.
const ESTIMATED_SITES = new Set(['luna2', 'venera7', 'venera13', 'viking1', 'viking2']);

const siteTier = (key) => (ESTIMATED_SITES.has(key) ? 'estimated' : 'measured');

// A craft that lands stops being an ephemeris and becomes a place, so it needs
// the tier its site is known to, not the tier its cruise was fitted to.
for (const mission of MISSIONS) {
  if (mission.surfaceAfter) mission.surfaceData = siteTier(mission.surfaceAfter.site);
}

const APOLLO_AGENCY = { agency: 'NASA', model: 'lm', kind: 'lander', sizeM: 4.2 };
const SITE_STYLE = {
  apollo11: APOLLO_AGENCY,
  apollo12: APOLLO_AGENCY,
  apollo14: APOLLO_AGENCY,
  apollo15: APOLLO_AGENCY,
  apollo16: APOLLO_AGENCY,
  apollo17: APOLLO_AGENCY,
};

export function landingSiteMissions(sites) {
  const out = [];
  for (const site of sites) {
    if (CLAIMED_SITES.has(site.key)) continue;
    const style = SITE_STYLE[site.key] ?? {};
    out.push({
      key: site.key,
      name: site.name,
      agency: style.agency ?? agencyForSite(site.key),
      kind: style.kind ?? 'lander',
      mission: site.crewed ? 'Crewed landing' : 'Robotic landing',
      target: site.body,
      launched: site.date,
      landed: site.date,
      surfaceAfter: { date: site.date, site: site.key },
      model: style.model ?? 'lander',
      sizeM: style.sizeM ?? 2.5,
      data: siteTier(site.key),
      surfaceData: siteTier(site.key),
      dataNote: ESTIMATED_SITES.has(site.key)
        ? 'Position known only approximately; see the note.'
        : 'Position measured from orbital imagery.',
      note: site.note,
      site: true,
    });
  }
  return out;
}

/**
 * Craft for a system nobody has been to.
 *
 * The point is architectural: nothing in the motion, render, picking, label or
 * inspector path is allowed to assume a spacecraft orbits a body of the Solar
 * System, and the way to keep that true is to have some that do not and to drive
 * them through exactly the same code as Voyager. What they are is invented,
 * which is what the procedural tier says and what every one of them is labelled
 * with; none of it is offered as a measurement of anything.
 *
 * Deterministic in the host name, so a system has the same fleet on every visit
 * rather than a new one each time it is loaded.
 *
 * @param {{host: string, bodies: Array<{
 *   key: string, name: string, radiusKm: number, gaseous?: boolean, airless?: boolean,
 * }>}} system
 */
export function proceduralCraft(system) {
  const out = [];
  const bodies = system.bodies.filter((b) => b.radiusKm > 200).slice(0, 4);
  if (!bodies.length) return out;

  // `body.key` is already unique across the system, so it only needs a suffix.
  const add = (body, index, kind, model, sizeM, name, mission, orbit, fix) => out.push({
    key: `${body.key}:c${index}`,
    name,
    agency: '',
    kind,
    mission,
    target: body.key,
    model,
    sizeM,
    orbit,
    fix,
    data: 'procedural',
    surfaceData: 'procedural',
    procedural: true,
    host: system.host,
    note: `Generated for ${system.host}. Nothing here was observed; the orbit and the hardware are both invented.`,
  });

  for (let i = 0; i < bodies.length; i++) {
    const body = bodies[i];
    const rnd = seededRandom(`${system.host}/${body.key}`);
    const mu = keplerMu(body.radiusKm, body.gaseous ? 1300 : 5000);
    const R = body.radiusKm;

    // A survey orbiter, on every body big enough to be worth surveying.
    add(
      body, 0, 'orbiter', 'probe', 3.4,
      `${body.name} Survey Probe`,
      `Mapping ${body.name} from a low orbit`,
      {
        centre: body.key,
        aKm: R * (1.12 + rnd() * 0.5),
        e: rnd() * 0.04,
        inclDeg: rnd() * 96,
        raanDeg: rnd() * 360,
        argpDeg: rnd() * 360,
        m0Deg: rnd() * 360,
        mu,
      },
    );

    // A station, on the innermost solid body only: one per system, where the
    // traffic would be.
    if (i === 0 && !body.gaseous) {
      add(
        body, 1, 'station', 'css', 58,
        `${body.name} Station`,
        `Crewed station in ${body.name} orbit`,
        {
          centre: body.key,
          aKm: R * (1.05 + rnd() * 0.12),
          e: 0.001,
          inclDeg: 20 + rnd() * 40,
          raanDeg: rnd() * 360,
          argpDeg: 0,
          m0Deg: rnd() * 360,
          mu,
        },
      );
    }

    // Something left behind, on a wide eccentric orbit that no longer looks
    // designed.
    if (rnd() > 0.45) {
      add(
        body, 2, 'debris', 'sphere', 2.2,
        `${body.name} Derelict`,
        'Derelict, no longer under control',
        {
          centre: body.key,
          aKm: R * (2.4 + rnd() * 6),
          e: 0.25 + rnd() * 0.35,
          inclDeg: rnd() * 180,
          raanDeg: rnd() * 360,
          argpDeg: rnd() * 360,
          m0Deg: rnd() * 360,
          mu,
        },
      );
    }

    // And a lander, on solid ground.
    if (!body.gaseous && rnd() > 0.4) {
      add(
        body, 3, 'lander', 'lander', 2.6,
        `${body.name} Lander`,
        `On the surface of ${body.name}`,
        null,
        { centre: body.key, latDeg: (rnd() - 0.5) * 140, lonDeg: (rnd() - 0.5) * 360 },
      );
    }
  }
  return out;
}

/** Standard gravitational parameter, km³/s², from a radius and a bulk density. */
function keplerMu(radiusKm, densityKgM3) {
  return 2.796e-10 * densityKgM3 * radiusKm * radiusKm * radiusKm;
}

/** Small deterministic generator, so a system's fleet is stable across visits. */
function seededRandom(text) {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return () => {
    h += 0x6d2b79f5;
    let t = h;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function agencyForSite(key) {
  if (key.startsWith('apollo') || key.startsWith('viking') || key === 'pathfinder') return 'NASA';
  if (key.startsWith('luna') || key.startsWith('venera')) return 'USSR';
  if (key.startsWith('change') || key === 'zhurong') return 'CNSA';
  if (key.startsWith('chandrayaan')) return 'ISRO';
  return '';
}

