/**
 * Spacecraft missions.
 *
 * JPL Horizons publishes fitted trajectory solutions for most flown spacecraft,
 * in the frame this renderer already uses: ecliptic of J2000, kilometres,
 * Sun-centred or planet-centred on request. So where a craft is in Horizons
 * there is nothing to model. Its measured path is sampled by
 * scripts/craft-fetch.mjs and interpolated at runtime, and the date the user
 * picks puts the spacecraft where it actually was.
 *
 * This file is the roster: identity, mission facts, and the sampling plan that
 * tells the fetch script which centre to ask for over which dates. It is the
 * single source of truth for both the build script and the renderer.
 *
 * WHAT IS NOT HERE, AND WHY
 *
 * Horizons has no trajectory for Magellan, the Viking orbiters, the Venera
 * landers, or any Apollo command or lunar module except Apollo 10's. Those
 * missions are not invented here. The ones that reached a surface appear as
 * landing sites in craft-data.js, at coordinates measured from orbital imagery;
 * the others are absent. A spacecraft with no data is better missing than
 * placed somewhere plausible and labelled as real.
 *
 * PROVENANCE
 *
 * Every craft carries a `data` field naming where its position comes from. The
 * renderer shows it, because a fitted trajectory and a guess should not look
 * alike:
 *
 *   'fitted'    Horizons trajectory solution, fitted to tracking data. The
 *               path shown is the path flown, to within metres or kilometres.
 *   'predicted' Horizons solution extrapolated past the last tracking data.
 *               Voyager has had no two-way tracking since 1992; the 2022 refit
 *               predicts to 2100 with a formal uncertainty of ~1.7 arcseconds.
 *   'elements'  Osculating elements sampled from Horizons and solved as a
 *               Kepler orbit between samples. Right to a few kilometres for a
 *               low orbit, and it drifts between samples.
 *   'measured'  A surface position measured from orbital imagery.
 *   'estimated' A surface position known only roughly, from tracking or from
 *               the absence of imagery.
 *
 * MOTION MODES
 *
 *   'path'      Sampled state vectors, interpolated with a Hermite spline.
 *               Used for cruise, flyby, escape and eccentric orbits.
 *   'elements'  Time series of osculating elements, Kepler-solved between.
 *               Used for fast repeating orbits, where a state-vector table of
 *               any useful density would be enormous.
 *   'surface'   Fixed to a body's surface at a latitude and longitude.
 *   'escape'    Straight-line asymptote from craft-data.js. Only a fallback.
 *
 * Segment `centre` is the body the samples are relative to. The renderer adds
 * that body's own position, exactly as it does for moons, so a craft stays
 * correctly placed against its parent even though the parent's own orbit comes
 * from this app's approximate elements rather than from DE441.
 */

